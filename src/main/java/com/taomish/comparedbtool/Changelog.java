package com.taomish.comparedbtool;

import java.net.InetAddress;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.UUID;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * The changelog table in the target database (like Liquibase DATABASECHANGELOG): every committed restore, load and change writes one row
 * per step in the same transaction as the change, so a rollback leaves no row. Failures and refusals get their own row afterwards.
 * Each row names its backup table, so the old rows and the undo are always findable. Backup tables that have no row (made by older
 * versions of the tool) are added as backfilled rows, so every machine shows the same history.
 */
final class Changelog {
    static final String TABLE = "cdt_changelog", LOCK = "cdt_changelog_lock";
    private static final Pattern BACKUP_NAME = Pattern.compile("^(restore|load|change)_(.+)_(\\d{14})$");
    private static final DateTimeFormatter STAMP = DateTimeFormatter.ofPattern("yyyyMMddHHmmss");
    private static final DateTimeFormatter SHOW = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    private Changelog() {}

    /** One tool invocation. All steps of a run share the run id. */
    static final class Run {
        final UUID id = UUID.randomUUID();
        final String schema, mode, ruleName, ruleFile, ruleSha, ticket, tool;
        final OffsetDateTime started = OffsetDateTime.now();
        String runDir;
        /** Set when this run puts an earlier run's change back: that run's rows become UNDONE. */
        UUID undoOf;

        Run(String schema, String mode, String ruleName, Path ruleFile, String ticket) {
            this.schema = schema; this.mode = mode; this.ruleName = ruleName; this.ticket = ticket;
            this.ruleFile = ruleFile == null ? null : ruleFile.toAbsolutePath().normalize().toString();
            this.ruleSha = ruleFile == null ? null : sha256(ruleFile);
            this.tool = BuildInfo.line();
        }

        void undoOf(String runId) { undoOf = runId == null || runId.isBlank() ? null : UUID.fromString(runId.strip()); }
    }

    /** One step of a run. Counts may be null when they do not apply. */
    record Entry(String stepId, String action, String table, String where, String statement, Long before, Long affected, Long after,
                 String preconditions, String risk, String backup, String undoRule) { }

    static String table(String schema) { return schema + "." + TABLE; }
    static String lockTable(String schema) { return schema + "." + LOCK; }

    static String sha256(Path file) {
        try {
            byte[] hash = MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(file));
            StringBuilder sb = new StringBuilder();
            for (byte b : hash) sb.append(String.format("%02x", b));
            return sb.toString();
        } catch (Exception e) { throw new ToolException("Cannot checksum rule file " + file + ": " + e.getMessage(), e); }
    }

    /** Creates the tables when missing and adds rows for backup tables nobody recorded. Uses an autocommit connection. */
    static void ensure(Connection c, String schema) throws SQLException {
        if (!DataRestorer.IDENTIFIER.matcher(schema).matches()) throw new ToolException("Invalid changelog schema " + schema);
        try (Statement st = c.createStatement()) {
            st.execute("CREATE TABLE IF NOT EXISTS " + table(schema) + " ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, run_id UUID NOT NULL, rule_name VARCHAR(500) NOT NULL, rule_file VARCHAR(2000), "
                + "rule_sha256 VARCHAR(100), ticket VARCHAR(200), mode VARCHAR(20) NOT NULL, step_id VARCHAR(500) NOT NULL, action VARCHAR(20) NOT NULL, "
                + "target_table VARCHAR(500), scope_where VARCHAR(100000), statement VARCHAR(100000), rows_before BIGINT, rows_affected BIGINT, rows_after BIGINT, "
                + "preconditions VARCHAR(100000), risk VARCHAR(2000), backup_table VARCHAR(500), undo_rule VARCHAR(2000), undo_of_run_id UUID, "
                + "status VARCHAR(20) NOT NULL, backfilled BOOLEAN NOT NULL DEFAULT FALSE, error VARCHAR(100000), db_user VARCHAR(200) NOT NULL DEFAULT CURRENT_USER, "
                + "os_user VARCHAR(200), host VARCHAR(200), tool_version VARCHAR(500), run_dir VARCHAR(2000), started_at TIMESTAMP WITH TIME ZONE NOT NULL, "
                + "finished_at TIMESTAMP WITH TIME ZONE)");
            st.execute("CREATE TABLE IF NOT EXISTS " + lockTable(schema) + " (id INT PRIMARY KEY, locked BOOLEAN, locked_by VARCHAR(500), locked_at TIMESTAMP WITH TIME ZONE)");
            try {
                st.executeUpdate("INSERT INTO " + lockTable(schema) + " (id, locked) SELECT 1, FALSE WHERE NOT EXISTS (SELECT 1 FROM " + lockTable(schema) + " WHERE id = 1)");
            } catch (SQLException duplicate) { /* two tools seeding at once: the other one won */ }
        }
        backfill(c, schema);
    }

    private static boolean exists(Connection c, String schema) throws SQLException {
        try (PreparedStatement ps = c.prepareStatement("SELECT count(*) FROM information_schema.tables WHERE lower(table_schema) = lower(?) AND lower(table_name) = ?")) {
            ps.setString(1, schema); ps.setString(2, TABLE);
            try (ResultSet rs = ps.executeQuery()) { rs.next(); return rs.getLong(1) > 0; }
        }
    }

    /** Backup tables (restore_*, load_*, change_*) without a changelog row get one: APPLIED, backfilled. Returns how many were added. */
    static int backfill(Connection c, String schema) throws SQLException {
        Set<String> known = new HashSet<>();
        try (Statement st = c.createStatement(); ResultSet rs = st.executeQuery("SELECT backup_table FROM " + table(schema) + " WHERE backup_table IS NOT NULL")) {
            while (rs.next()) known.add(rs.getString(1).toLowerCase(Locale.ROOT));
        }
        List<String> names = new ArrayList<>();
        try (PreparedStatement ps = c.prepareStatement("SELECT table_name FROM information_schema.tables WHERE lower(table_schema) = lower(?)")) {
            ps.setString(1, schema);
            try (ResultSet rs = ps.executeQuery()) { while (rs.next()) names.add(rs.getString(1).toLowerCase(Locale.ROOT)); }
        }
        int added = 0;
        for (String name : names) {
            Matcher m = BACKUP_NAME.matcher(name);
            if (!m.matches() || known.contains((schema + "." + name).toLowerCase(Locale.ROOT))) continue;
            OffsetDateTime when;
            try { when = LocalDateTime.parse(m.group(3), STAMP).atZone(java.time.ZoneId.systemDefault()).toOffsetDateTime(); }
            catch (Exception e) { continue; }
            long rows;
            try (Statement st = c.createStatement(); ResultSet rs = st.executeQuery("SELECT count(*) FROM " + schema + "." + name)) { rs.next(); rows = rs.getLong(1); }
            String mode = m.group(1).toUpperCase(Locale.ROOT);
            try (PreparedStatement ps = c.prepareStatement("INSERT INTO " + table(schema) + " (run_id, rule_name, mode, step_id, action, rows_before, backup_table, status, "
                + "backfilled, os_user, started_at, finished_at) VALUES (?, ?, ?, ?, ?, ?, ?, 'APPLIED', TRUE, 'backfilled', ?, ?)")) {
                ps.setObject(1, UUID.randomUUID()); ps.setString(2, m.group(2)); ps.setString(3, mode); ps.setString(4, "(backfilled)");
                ps.setString(5, mode.equals("LOAD") ? "INSERT" : mode); ps.setLong(6, rows); ps.setString(7, schema + "." + name);
                ps.setObject(8, when); ps.setObject(9, when);
                ps.executeUpdate();
                added++;
            }
        }
        return added;
    }

    /** Takes the apply lock for the rest of the transaction (released by commit or rollback). A second apply fails at once on PostgreSQL. */
    static void lock(Connection c, String schema, String who) throws SQLException {
        boolean postgres = c.getMetaData().getDatabaseProductName().toLowerCase(Locale.ROOT).contains("postgres");
        try (Statement st = c.createStatement(); ResultSet rs = st.executeQuery("SELECT locked FROM " + lockTable(schema) + " WHERE id = 1 FOR UPDATE" + (postgres ? " NOWAIT" : ""))) {
            if (!rs.next()) throw new ToolException("Changelog lock row is missing in " + lockTable(schema));
        } catch (SQLException e) {
            if ("55P03".equals(e.getSQLState()))
                throw new ToolException("Another apply is running on this database (it holds the lock in " + lockTable(schema) + "). Wait for it to finish and run again.");
            throw e;
        }
        try (PreparedStatement ps = c.prepareStatement("UPDATE " + lockTable(schema) + " SET locked = TRUE, locked_by = ?, locked_at = ? WHERE id = 1")) {
            ps.setString(1, who); ps.setObject(2, OffsetDateTime.now()); ps.executeUpdate();
        }
    }

    /** Earlier APPLIED runs of this rule name: [run id, started, same checksum?]. Used by the re-apply guard of --change. */
    static List<String[]> earlierApplied(Connection c, Run run) throws SQLException {
        List<String[]> out = new ArrayList<>();
        try (PreparedStatement ps = c.prepareStatement("SELECT DISTINCT run_id, started_at, rule_sha256 FROM " + table(run.schema)
            + " WHERE rule_name = ? AND mode = 'CHANGE' AND status = 'APPLIED' AND backfilled = FALSE ORDER BY started_at DESC")) {
            ps.setString(1, run.ruleName);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) out.add(new String[]{rs.getString(1), String.valueOf(rs.getObject(2, OffsetDateTime.class).format(SHOW)),
                    run.ruleSha != null && run.ruleSha.equals(rs.getString(3)) ? "same" : "different"});
            }
        }
        return out;
    }

    /** Writes the rows of a run with one status. APPLIED rows of an undo run also mark the original run UNDONE. Caller commits. */
    static void record(Connection c, Run run, List<Entry> entries, String status, String error) throws SQLException {
        String user = System.getProperty("user.name"), host = host();
        try (PreparedStatement ps = c.prepareStatement("INSERT INTO " + table(run.schema) + " (run_id, rule_name, rule_file, rule_sha256, ticket, mode, step_id, action, "
            + "target_table, scope_where, statement, rows_before, rows_affected, rows_after, preconditions, risk, backup_table, undo_rule, undo_of_run_id, status, error, "
            + "os_user, host, tool_version, run_dir, started_at, finished_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)")) {
            for (Entry e : entries) {
                int i = 1;
                ps.setObject(i++, run.id); ps.setString(i++, run.ruleName); ps.setString(i++, run.ruleFile); ps.setString(i++, run.ruleSha);
                ps.setString(i++, run.ticket); ps.setString(i++, run.mode); ps.setString(i++, e.stepId()); ps.setString(i++, e.action());
                ps.setString(i++, e.table()); ps.setString(i++, e.where()); ps.setString(i++, e.statement());
                ps.setObject(i++, e.before()); ps.setObject(i++, e.affected()); ps.setObject(i++, e.after());
                ps.setString(i++, e.preconditions()); ps.setString(i++, e.risk()); ps.setString(i++, e.backup()); ps.setString(i++, e.undoRule());
                ps.setObject(i++, run.undoOf); ps.setString(i++, status); ps.setString(i++, error);
                ps.setString(i++, user); ps.setString(i++, host); ps.setString(i++, run.tool); ps.setString(i++, run.runDir);
                ps.setObject(i++, run.started); ps.setObject(i, OffsetDateTime.now());
                ps.executeUpdate();
            }
        }
        if ("APPLIED".equals(status)) {
            try (Statement st = c.createStatement()) { st.executeUpdate("UPDATE " + lockTable(run.schema) + " SET locked = FALSE WHERE id = 1"); }
        }
        if (run.undoOf != null && "APPLIED".equals(status)) {
            try (PreparedStatement ps = c.prepareStatement("UPDATE " + table(run.schema) + " SET status = 'UNDONE' WHERE run_id = ? AND status = 'APPLIED' AND mode <> 'UNDO'")) {
                ps.setObject(1, run.undoOf); ps.executeUpdate();
            }
        }
    }

    /** A FAILED / ROLLED_BACK row in its own short transaction, after the change was rolled back. Never throws: the original error matters more. */
    static void failure(Connection c, Run run, String status, String error) {
        try {
            c.rollback();
            record(c, run, List.of(new Entry("-", run.mode.equals("LOAD") ? "INSERT" : run.mode.equals("UNDO") ? "RESTORE" : run.mode, null, null, null, null, null, null,
                null, null, null, null)), status, error);
            c.commit();
        } catch (Exception e) {
            try { c.rollback(); } catch (SQLException ignored) { /* nothing more to do */ }
        }
    }

    private static String host() {
        try { return InetAddress.getLocalHost().getHostName(); } catch (Exception e) { return null; }
    }

    static String who() { return System.getProperty("user.name") + "@" + host(); }

    /** The text of --changelog: newest first, with the backup table and whether it still exists. */
    static List<String> report(Connection c, String schema, String rule, String ticket, int last, boolean backfill) throws SQLException {
        List<String> lines = new ArrayList<>();
        if (!exists(c, schema)) {
            if (!backfill) return List.of("No changelog in schema " + schema + " yet: nothing has been applied through the tool here.");
            ensure(c, schema);
        } else if (backfill) backfill(c, schema);
        StringBuilder sql = new StringBuilder("SELECT id, run_id, started_at, mode, rule_name, step_id, action, target_table, rows_before, rows_affected, rows_after, risk, status, "
            + "backfilled, backup_table, undo_rule, undo_of_run_id, os_user, host, db_user, error FROM " + table(schema) + " WHERE 1 = 1");
        if (rule != null) sql.append(" AND rule_name = ?");
        if (ticket != null) sql.append(" AND ticket = ?");
        sql.append(" ORDER BY id DESC FETCH FIRST ").append(Math.max(1, last)).append(" ROWS ONLY");
        try (PreparedStatement ps = c.prepareStatement(sql.toString())) {
            int i = 1;
            if (rule != null) ps.setString(i++, rule);
            if (ticket != null) ps.setString(i, ticket);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    String backup = rs.getString("backup_table");
                    String backupInfo = backup == null ? "NO BACKUP" : backup + " " + backupState(c, backup);
                    lines.add(String.format(Locale.ROOT, "#%d %s %s %s step %s %s %s  before %s affected %s after %s  [%s%s%s]  by %s  %s%s run %s",
                        rs.getLong("id"), rs.getObject("started_at", OffsetDateTime.class).format(SHOW), rs.getString("mode"), rs.getString("rule_name"),
                        rs.getString("step_id"), rs.getString("action"), nz(rs.getString("target_table")), nz(rs.getObject("rows_before")), nz(rs.getObject("rows_affected")),
                        nz(rs.getObject("rows_after")), rs.getString("status"), rs.getBoolean("backfilled") ? ", backfilled" : "",
                        rs.getString("risk") == null ? "" : ", " + rs.getString("risk"),
                        rs.getString("os_user") == null ? rs.getString("db_user") : rs.getString("os_user") + "@" + nz(rs.getString("host")) + " as " + rs.getString("db_user"),
                        "backup " + backupInfo, rs.getString("undo_rule") == null ? "" : "  undo " + rs.getString("undo_rule"),
                        rs.getString("run_id").substring(0, 8)) + (rs.getString("undo_of_run_id") == null ? "" : " (undo of " + rs.getString("undo_of_run_id").substring(0, 8) + ")")
                        + (rs.getString("error") == null ? "" : "  ERROR: " + shorten(rs.getString("error"))));
                }
            }
        }
        if (lines.isEmpty()) lines.add("The changelog in " + schema + " has no rows for this filter.");
        return lines;
    }

    /** --changelog: opens the datasource, backfills when writing is allowed, returns the lines to print. */
    static List<String> show(DatasourceSettings settings, Cli.Options options) throws Exception {
        var definition = settings.getDatasources().get(options.db);
        if (definition == null) throw new ToolException(DatasourceSettings.unknownDatasourceMessage(options.db));
        if (QueryRunner.production(options.db, definition) && !options.allowProd) throw new ToolException("Datasource " + options.db + " requires --allow-prod");
        String schema = options.changelogSchema == null ? "parity_work" : options.changelogSchema;
        com.zaxxer.hikari.HikariConfig config = new com.zaxxer.hikari.HikariConfig();
        config.setJdbcUrl(definition.getUrl()); config.setUsername(definition.getUsername()); config.setPassword(definition.getPassword());
        if (definition.getDriverClassName() != null) config.setDriverClassName(definition.getDriverClassName());
        config.setMaximumPoolSize(1); config.setMinimumIdle(0); config.setAutoCommit(true);
        config.setConnectionTimeout(30_000); config.setInitializationFailTimeout(-1);
        try (var pool = new com.zaxxer.hikari.HikariDataSource(config); Connection c = pool.getConnection()) {
            return report(c, schema, options.changelogRule, options.changelogTicket, options.last, definition.isAllowWrite());
        }
    }

    private static String backupState(Connection c, String backup) {
        try (Statement st = c.createStatement(); ResultSet rs = st.executeQuery("SELECT count(*) FROM " + backup)) {
            rs.next(); return "(" + rs.getLong(1) + " rows)";
        } catch (SQLException e) {
            try { c.rollback(); } catch (SQLException ignored) { /* read only */ }
            return "(dropped)";
        }
    }

    private static String nz(Object value) { return value == null ? "-" : String.valueOf(value); }
    private static String shorten(String text) { String flat = text.replaceAll("\\s+", " "); return flat.length() > 160 ? flat.substring(0, 157) + "..." : flat; }

    static String stamp() { return LocalDateTime.now().format(STAMP); }
}
