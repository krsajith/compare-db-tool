package com.taomish.comparedbtool;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/** Finds rule files for the menu and tells what kind each is, without connecting to anything. */
final class RuleCatalog {
    private RuleCatalog() {}

    enum Kind {
        COMPARE("compare"), RESTORE("restore"), TEMPLATE_IMPORT("template import"), TEMPLATE_EXPORT("template export");
        final String label;
        Kind(String label) { this.label = label; }
        boolean writes() { return this == RESTORE || this == TEMPLATE_IMPORT; }
    }

    record Entry(Path path, String name, Kind kind, String description) {
        String key() { return path.toString().replace('\\', '/'); }
    }

    private static final JsonMapper JSON = JsonMapper.builder().build();
    private static final Pattern COMMENT = Pattern.compile("<!--(.*?)-->", Pattern.DOTALL);

    static List<Entry> scan(Path directory) {
        List<Entry> entries = new ArrayList<>();
        if (!Files.isDirectory(directory)) return entries;
        try (Stream<Path> files = Files.list(directory)) {
            files.filter(Files::isRegularFile).sorted(Comparator.comparing(p -> p.getFileName().toString().toLowerCase(Locale.ROOT))).forEach(p -> {
                Entry entry = describe(p);
                if (entry != null) entries.add(entry);
            });
        } catch (IOException e) { /* an unreadable folder just lists nothing */ }
        return entries;
    }

    /** Null when the file is not a rule this tool can run. */
    static Entry describe(Path file) {
        String fileName = file.getFileName().toString();
        String lower = fileName.toLowerCase(Locale.ROOT);
        try {
            if (lower.endsWith(".xml")) {
                String head = Files.readString(file);
                if (!head.contains("<rules")) return null;
                Matcher m = COMMENT.matcher(head.substring(0, Math.min(head.length(), 6000)));
                return new Entry(file, base(fileName), Kind.COMPARE, m.find() ? tidy(m.group(1)) : "");
            }
            if (lower.endsWith(".json")) {
                JsonNode node = JSON.readTree(Files.readString(file));
                if (node == null || !node.isObject()) return null;
                String description = node.has("description") ? node.get("description").asString() : "";
                if (node.has("steps")) return new Entry(file, base(fileName), Kind.RESTORE, tidy(description));
                if (node.has("mode") || node.has("file")) return new Entry(file, base(fileName), Kind.TEMPLATE_IMPORT, tidy(description));
                if (node.has("templates")) return new Entry(file, base(fileName), Kind.TEMPLATE_EXPORT, tidy(description));
            }
        } catch (Exception e) { /* not readable as a rule: leave it out of the list */ }
        return null;
    }

    private static String base(String fileName) { return fileName.replaceFirst("\\.[^.]+$", ""); }

    /** One line: whitespace collapsed, cut at a sentence end or 110 characters. */
    static String tidy(String text) {
        String flat = text == null ? "" : text.replaceAll("\\s+", " ").strip();
        flat = flat.replaceFirst("^Generated by \\S+\\.py\\.?\\s*", "");   // a generator note says nothing about the rule
        int stop = flat.indexOf(". ");
        if (stop >= 10 && stop < 110) flat = flat.substring(0, stop + 1);
        return flat.length() > 110 ? flat.substring(0, 107) + "..." : flat;
    }
}
